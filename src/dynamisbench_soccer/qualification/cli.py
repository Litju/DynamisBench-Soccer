"""``dbs qualification ...`` commands (RES-692)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from dynamisbench_soccer.qualification.models import (
    DIMENSIONS,
    M3_GATE,
    BlockerKind,
    DimState,
    Ledger,
    compute_state,
    gate_met,
    is_blocked,
    load,
    validate,
)
from dynamisbench_soccer.registry.models import load as load_registry

LEDGER_DOC = Path("docs/qualification-ledger.md")
_CELL = {
    DimState.ABSENT: "-",
    DimState.PARTIAL: "part",
    DimState.SPECIFIED: "spec",
    DimState.VERIFIED: "**ver**",
}


def ledger_markdown(ledger: Ledger) -> str:
    in_scope = ledger.in_scope()
    passing = [f for f in in_scope if compute_state(f).rank >= M3_GATE.rank]
    verdict = "MET" if gate_met(ledger) else "NOT MET"
    lines = [
        f"# Device-family qualification ledger v{ledger.version}",
        "",
        "<!-- GENERATED by `dbs qualification ledger --write` from qualification/ledger.toml; "
        "do not edit by hand. -->",
        "",
        "Issue RES-692. Architecture: [m3-architecture.md](m3-architecture.md). Family "
        "states are **computed** from the dimension records and are never declared by hand.",
        "",
        f"**M3 gate ({M3_GATE.value} for every in-scope family): {verdict}**, "
        f"with {len(passing)} of {len(in_scope)} families passing.",
        "",
        "Cells: `-` absent, `part` partial, `spec` specified, `ver` verified. "
        "**Blocked** means at least one scientific blocker is open.",
        "",
        "## Families",
        "",
        "| # | Family | Paradigm | Engine | " + " | ".join(DIMENSIONS) + " | State | Blocked |",
        "| -- | -- | -- | -- | " + " | ".join("--" for _ in DIMENSIONS) + " | -- | -- |",
    ]
    for fam in ledger.family:
        cells = " | ".join(_CELL[d.state] for d in fam.dims.values())
        blocked = "**blocked**" if is_blocked(fam) else "no"
        lines.append(
            f"| {fam.number} | {fam.name} (`{fam.id}`) | {fam.paradigm.value} | "
            f"{fam.engine_issue} | {cells} | {compute_state(fam).value} | {blocked} |"
        )
    lines += [
        "",
        "9. Additional classes enter only through the admission contract "
        f"({ledger.admission.issue}). {ledger.admission.rule}",
        "",
        "## Dimensions",
        "",
        "| Id | Dimension |",
        "| -- | -- |",
    ]
    lines += [f"| {k} | {v} |" for k, v in DIMENSIONS.items()]
    lines += ["", "## Open blockers", ""]
    for kind in (BlockerKind.SCIENTIFIC, BlockerKind.DEPENDENCY):
        lines += [f"### {kind.value.capitalize()}", "", "| Family | Dim | Issue | Blocker |",
                  "| -- | -- | -- | -- |"]  # fmt: skip
        for fam in ledger.family:
            for key, dim in fam.dims.items():
                for b in dim.blockers:
                    if b.kind is kind:
                        lines.append(f"| `{fam.id}` | {key} | {b.issue} | {b.text} |")
        lines.append("")
    lines += ["## Dimension owners", "", "| Family | " + " | ".join(DIMENSIONS) + " |",
              "| -- | " + " | ".join("--" for _ in DIMENSIONS) + " |"]  # fmt: skip
    for fam in ledger.family:
        owners = " | ".join(d.owner.removeprefix("RES-") for d in fam.dims.values())
        lines.append(f"| `{fam.id}` | {owners} |")
    lines += ["", "Owners are RES issue numbers.", "", "## Assessment science engines", "",
              "| Engine | Issue | Tests | Device families |", "| -- | -- | -- | -- |"]  # fmt: skip
    for a in ledger.assessment:
        tests = ", ".join(f"`{t}`" for t in a.tests)
        fams = ", ".join(f"`{f}`" for f in a.device_families)
        lines.append(f"| {a.name} | {a.issue} | {tests} | {fams} |")
    lines += ["", "## Declared non-equivalences", "",
              "| Id | A | B | Statement | Study | Verdict |",
              "| -- | -- | -- | -- | -- | -- |"]  # fmt: skip
    for n in ledger.non_equivalence:
        verdict_text = n.verdict.value if n.verdict else "open"
        lines.append(f"| {n.id} | `{n.a}` | `{n.b}` | {n.statement} | {n.study} | {verdict_text} |")
    lines += ["", "## Quality-parity principles", "", "| Id | Principle | Enforced by |",
              "| -- | -- | -- |"]  # fmt: skip
    lines += [f"| {p.id} | {p.text} | {p.enforced_by} |" for p in ledger.principle]
    return "\n".join(lines) + "\n"


def _load(args: argparse.Namespace) -> tuple[Ledger, list[str]]:
    ledger = load(Path(args.root))
    problems = validate(ledger, load_registry(Path(args.registry)), Path(args.repo_root))
    return ledger, problems


def _cmd_validate(args: argparse.Namespace) -> int:
    ledger, problems = _load(args)
    for p in problems:
        print(f"FAIL {p}", file=sys.stderr)
    for fam in ledger.family:
        flag = " [blocked]" if is_blocked(fam) else ""
        print(f"{fam.number}. {fam.id:<22} {compute_state(fam).value}{flag}")
    print(f"qualification ledger: {len(ledger.family)} families: "
          f"{'OK' if not problems else f'{len(problems)} problem(s)'}")  # fmt: skip
    return 1 if problems else 0


def _cmd_ledger(args: argparse.Namespace) -> int:
    text = ledger_markdown(load(Path(args.root)))
    target = Path(args.doc)
    if args.write:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {target}")
    elif args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print(f"FAIL {target} out of date; run `dbs qualification ledger --write`")
            return 1
        print(f"{target} up to date")
    else:
        print(text)
    return 0


def _cmd_gate(args: argparse.Namespace) -> int:
    """Exit 0 only when every in-scope family meets the M3 gate (used by RES-675)."""
    ledger, problems = _load(args)
    if problems:
        for p in problems:
            print(f"FAIL {p}", file=sys.stderr)
        return 1
    failing = [f for f in ledger.in_scope() if compute_state(f).rank < M3_GATE.rank]
    for fam in failing:
        print(f"NOT MET {fam.id}: {compute_state(fam).value}"
              f"{' [blocked]' if is_blocked(fam) else ''}")  # fmt: skip
    print(f"M3 gate ({M3_GATE.value}): {'MET' if not failing else 'NOT MET'}")
    return 0 if not failing else 1


def register(sub: argparse._SubParsersAction) -> None:  # type: ignore[type-arg]
    q = sub.add_parser("qualification", help="device-family qualification ledger (M3)")
    qsub = q.add_subparsers(dest="qualification_command", required=True)

    def common(p: argparse.ArgumentParser) -> None:
        p.add_argument("--root", default="qualification")
        p.add_argument("--registry", default="registry")
        p.add_argument("--repo-root", default=".")

    v = qsub.add_parser("validate", help="validate the ledger and print computed states")
    common(v)
    v.set_defaults(handler=_cmd_validate)
    g = qsub.add_parser("gate", help="exit 0 only if every in-scope family meets the M3 gate")
    common(g)
    g.set_defaults(handler=_cmd_gate)
    m = qsub.add_parser("ledger", help="render the ledger as Markdown")
    m.add_argument("--root", default="qualification")
    m.add_argument("--doc", default=str(LEDGER_DOC))
    mode = m.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    m.set_defaults(handler=_cmd_ledger)
