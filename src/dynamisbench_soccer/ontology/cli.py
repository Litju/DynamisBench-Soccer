"""``dbs ontology ...`` commands."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from dynamisbench_soccer.ontology.boundaries import screen
from dynamisbench_soccer.ontology.models import COMPETENCIES, Bundle, load, validate
from dynamisbench_soccer.registry.models import load as load_registry

MATRIX_DOC = Path("docs/coverage-matrix.md")
_SYMBOL = {"core": "**core**", "extension": "ext", "out": "-"}


def matrix_markdown(bundle: Bundle) -> str:
    names = {c.id: c.name for c in bundle.ontology.competency}
    lines = [
        "# Coverage matrix v" + bundle.coverage.version,
        "",
        "<!-- GENERATED by `dbs ontology matrix --write` from ontology/coverage.toml; "
        "do not edit by hand. -->",
        "",
        "`core` = required in v0.1 tasks, `ext` = extension (v0.2+ or optional), "
        "`-` = out of scope.",
        "",
        "| Test | " + " | ".join(f"{c} {names[c]}" for c in COMPETENCIES) + " |",
        "| -- | " + " | ".join("--" for _ in COMPETENCIES) + " |",
    ]
    tests = {t.id: t.name for t in bundle.ontology.test}
    for row in bundle.coverage.row:
        cells = " | ".join(_SYMBOL[row.cell(c)] for c in COMPETENCIES)
        lines.append(f"| `{row.test}` {tests[row.test]} | {cells} |")
    lines += ["", "## Context values", "", "| Dimension | Value | Status |", "| -- | -- | -- |"]
    for dim, values in bundle.coverage.context.items():
        for value, status in values.items():
            lines.append(f"| {dim} | `{value}` | {_SYMBOL[status]} |")
    return "\n".join(lines) + "\n"


def _cmd_validate(args: argparse.Namespace) -> int:
    bundle = load(Path(args.root))
    problems = validate(bundle, load_registry(Path(args.registry)))
    for p in problems:
        print(f"FAIL {p}", file=sys.stderr)
    n_rules = len(bundle.boundaries.rule)
    print(f"ontology: {len(bundle.ontology.test)} tests, {n_rules} boundary rules: "
          f"{'OK' if not problems else f'{len(problems)} problem(s)'}")  # fmt: skip
    return 1 if problems else 0


def _cmd_matrix(args: argparse.Namespace) -> int:
    text = matrix_markdown(load(Path(args.root)))
    target = Path(args.doc)
    if args.write:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {target}")
    elif args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print(f"FAIL {target} out of date; run `dbs ontology matrix --write`")
            return 1
        print(f"{target} up to date")
    else:
        print(text)
    return 0


def _cmd_screen(args: argparse.Namespace) -> int:
    bundle = load(Path(args.root))
    text = Path(args.file).read_text(encoding="utf-8") if args.file else sys.stdin.read()
    hits = screen(text, bundle.boundaries)
    for h in hits:
        print(f"{h.rule_id} [{h.severity}] {h.excerpt}")
    return 1 if hits else 0


def register(sub: argparse._SubParsersAction) -> None:  # type: ignore[type-arg]
    onto = sub.add_parser("ontology", help="ontology, coverage matrix, decision boundaries")
    osub = onto.add_subparsers(dest="ontology_command", required=True)
    v = osub.add_parser("validate", help="cross-check ontology, coverage and registry")
    v.add_argument("--root", default="ontology")
    v.add_argument("--registry", default="registry")
    v.set_defaults(handler=_cmd_validate)
    m = osub.add_parser("matrix", help="render the coverage matrix")
    m.add_argument("--root", default="ontology")
    m.add_argument("--doc", default=str(MATRIX_DOC))
    mode = m.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    m.set_defaults(handler=_cmd_matrix)
    s = osub.add_parser("screen", help="reference boundary screen over text (stdin or file)")
    s.add_argument("--root", default="ontology")
    s.add_argument("--file", default=None)
    s.set_defaults(handler=_cmd_screen)
