# ruff: noqa: E501
"""Build docs/verification/engine-v0.1.{json,md} from the executable matrix and the ledger.

    uv run python scripts/build_verification.py          # write
    uv run python scripts/build_verification.py --check # fail when committed files are stale

Everything in the report is computed: case outcomes come from running the engines, states and
the M3 gate come from the ledger. Nothing is hand-edited.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

import e2e_cases  # noqa: E402

from dynamisbench_soccer.qualification import interface  # noqa: E402
from dynamisbench_soccer.qualification import ledger as ledger_model  # noqa: E402
from dynamisbench_soccer.qualification.state import computed_states, m3_gate  # noqa: E402

JSON_PATH = ROOT / "docs/verification/engine-v0.1.json"
MD_PATH = ROOT / "docs/verification/engine-v0.1.md"
DISPOSITION = ROOT / "docs/verification/m3-disposition.md"
AGREEMENT = ROOT / "docs/verification/cross-device-agreement.json"
ASSESSMENT_DOCS = {
    "Jumps (RES-671)": "docs/jump-assessment.md",
    "Isometric (RES-672)": "docs/isometric-assessment.md",
    "Sprint/COD (RES-673)": "docs/sprint-cod-assessment.md",
}


def _round(value, digits=6):
    if isinstance(value, float):
        return round(value, digits)
    if isinstance(value, dict):
        return {k: _round(v, digits) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_round(v, digits) for v in value]
    return value


def build() -> tuple[dict, str]:
    model = ledger_model.load(ROOT / "qualification/ledger.toml")
    states = computed_states(model, ROOT)
    gate = m3_gate(model, ROOT)
    rows = e2e_cases.run_all()
    coverage: dict[str, dict[str, list[str]]] = {}
    for r in rows:
        family = coverage.setdefault(r["family"], {a: [] for a in e2e_cases.AXES})
        for axis, value in r["axes"].items():
            if value not in family[axis]:
                family[axis].append(value)
    for family in coverage.values():
        for axis in family:
            family[axis].sort()
    agreement = json.loads(AGREEMENT.read_text())
    capability = {}
    for s in sorted(model.subfamilies, key=lambda s: s.id):
        evidence = [e for e in model.evidence if e.subfamily == s.id and e.dimension in {"G", "H"}]
        capability[s.id] = {
            label: any(e.ref == f"repo:{path}" for e in evidence)
            for label, path in ASSESSMENT_DOCS.items()
        }
    payload = {
        "interface_version": interface.INTERFACE_VERSION,
        "cases": rows,
        "case_totals": {
            "total": len(rows),
            "passed": sum(r["passed"] for r in rows),
            "failed": [f"{r['subfamily']}/{r['case']}" for r in rows if not r["passed"]],
        },
        "coverage": coverage,
        "m3_gate": asdict(gate),
        "states": [asdict(s) for s in states],
        "capability": capability,
        "agreement_counts": agreement["classification_counts"],
    }
    return _round(payload), markdown(payload, agreement)


def markdown(p: dict, agreement: dict) -> str:
    gate = p["m3_gate"]
    totals = p["case_totals"]
    out = [
        "# engine-v0.1 verification report",
        "",
        "<!-- GENERATED by scripts/build_verification.py; do not edit -->",
        "",
        "Everything below is computed from executable cases and the qualification ledger.",
        "Engineering calculations only; no scientific qualification of any device or metric.",
        "",
        "## 1. M3 gate (computed)",
        "",
        f"* **M3 gate passed: {gate['passed']}.** {gate['engineering_verified']}/{gate['total_subfamilies']}"
        f" subfamilies are ENGINEERING_VERIFIED. State counts: {json.dumps(gate['by_state'], sort_keys=True)}.",
        f"* Ledger structural problems: {len(gate['structural_problems'])}.",
        "* Policy A: ENGINEERING_VERIFIED means computational-reference readiness. It requires A-M",
        "  and O verified by substantive independent receipts, an independent reference and no",
        "  open computational blocker. It says nothing about physical-device validity, which is",
        "  reported separately (section 2b). N belongs to M4/M5 and sign-off to M8.",
        f"* Receipt problems: {sum(len(v) for v in gate['receipt_problems'].values())}; "
        f"empirical-record problems: {sum(len(v) for v in gate['empirical_problems'].values())}.",
        "",
        "## 2. Subfamily states, blockers, owners and required experiments",
        "",
        "| Subfamily | State | Independent reference | Unverified A-M,O |",
        "| -- | -- | -- | -- |",
    ]
    for s in p["states"]:
        out.append(
            f"| {s['subfamily']} | {s['state']} | {'yes' if s['independent_reference'] else 'no'} "
            f"| {len(s['unverified_m3'])} of 14 |"
        )
    out += ["", "### Blockers and the experiment that would clear them", ""]
    for s in p["states"]:
        out.append(f"**{s['subfamily']}** ({s['state']})")
        for b in s["blockers"]:
            out.append(f"* computational blocker: {b}")
        owners = {}
        for d in s["unverified_m3"]:
            owners.setdefault((s["owners"][d], s["required_computational"][d]), []).append(d)
        for (owner, requirement), dims in sorted(owners.items()):
            out.append(f"* {','.join(dims)} - owner {owner}: {requirement}")
        out.append("")
    out += [
        "## 2b. Empirical device-validity evidence (separate from the computational gate)",
        "",
        "| Subfamily | Measured records | Dimensions covered | Interchangeability |",
        "| -- | -- | -- | -- |",
    ]
    for s in p["states"]:
        out.append(
            f"| {s['subfamily']} | {len(s['empirical_records'])} "
            f"| {','.join(s['empirical_dimensions_covered']) or 'none'} "
            f"| {s['empirical_interchangeability']} |"
        )
    out += ["", "Open empirical requirements (what only physical measurement can close):", ""]
    for s in p["states"]:
        out.append(f"**{s['subfamily']}**")
        for g in s["empirical_gaps"]:
            out.append(f"* gap: {g}")
        out.append(
            "* needs measured evidence for: "
            + ", ".join(sorted(s["empirical_requirements"]))
            + " (see docs/verification/m3-gate-policy-decision.md)"
        )
        out.append("")
    out += [
        "## 3. Dimension ratings by subfamily",
        "",
        "| Subfamily | " + " | ".join("ABCDEFGHIJKLMNO") + " |",
        "| -- |" + " -- |" * 15,
    ]
    short = {
        "absent": "-",
        "partial": "p",
        "specified": "s",
        "verified": "V",
        "not_applicable": "n/a",
    }
    for s in p["states"]:
        out.append(
            f"| {s['subfamily']} | "
            + " | ".join(short[s["ratings"][d]] for d in "ABCDEFGHIJKLMNO")
            + " |"
        )
    out += [
        "",
        "`-` absent, `p` partial (implemented, checked against analytical references), `s` specified, `V` verified.",
        "",
    ]
    out += [
        "## 4. Device family x assessment capability",
        "",
        "| Subfamily | " + " | ".join(ASSESSMENT_DOCS) + " |",
        "| -- |" + " -- |" * len(ASSESSMENT_DOCS),
    ]
    for sub, caps in p["capability"].items():
        out.append(
            f"| {sub} | " + " | ".join("yes" if caps[k] else "-" for k in ASSESSMENT_DOCS) + " |"
        )
    out += ["", "Entries come from G/H ledger evidence pointing at each assessment document.", ""]
    out += [
        "## 5. End-to-end numerical verification matrix",
        "",
        f"{totals['passed']}/{totals['total']} cases passed. Failed: {totals['failed'] or 'none'}.",
        "",
        "| Family | Cases | Native rates (Hz) | Filters | Event/onset | Diff./integration | Calibration/geometry | Corruption | Eligibility | Refusal |",
        "| -- | -- | -- | -- | -- | -- | -- | -- | -- | -- |",
    ]
    counts = {}
    for r in p["cases"]:
        counts[r["family"]] = counts.get(r["family"], 0) + 1
    for family, axes in sorted(p["coverage"].items()):
        cells = [", ".join(v for v in axes[a] if v != "-") or "-" for a in e2e_cases.AXES]
        out.append(f"| {family} | {counts[family]} | " + " | ".join(cells) + " |")
    out += [
        "",
        "### Cases",
        "",
        "| Subfamily | Case | Chain | Observed | Expected | Tolerance | Result |",
        "| -- | -- | -- | -- | -- | -- | -- |",
    ]
    for r in p["cases"]:

        def cell(v):
            return "" if v is None else (f"{v:.6g}" if isinstance(v, float) else str(v))

        out.append(
            f"| {r['subfamily']} | {r['case']} | {r['chain']} | {cell(r['observed'])} | {cell(r['expected'])} "
            f"| {cell(r['tolerance'])} | {'pass' if r['passed'] else 'FAIL'} |"
        )
    out += ["", "## 6. Cross-device comparisons and their evidence basis", ""]
    out.append(
        f"Classification counts: {json.dumps(agreement['classification_counts'], sort_keys=True)}; "
        f"interchangeable claims: {agreement['interchangeable_claims']}; empirical device agreement studies: "
        f"{agreement['empirical_device_agreement_studies']}."
    )
    out += [
        "",
        "| Comparison | Quantity | Left / right execution | Class |",
        "| -- | -- | -- | -- |",
    ]
    for s in agreement["studies"]:
        basis = " / ".join(s["execution_basis"])
        out.append(
            f"| {s['left']} vs {s['right']} | {s['quantity']} | {basis} | {s['classification']} |"
        )
    out += [
        "",
        "Analytical model agreement, empirical device agreement, unsupported comparison, missing evidence and",
        "definition mismatch are separate states (docs/cross-device-agreement.md). Synthetic agreement never",
        "establishes interchangeability.",
        "",
        "## 7. Frozen interface",
        "",
        f"`{p['interface_version']}`: `docs/verification/engine-v0.1-interface.json` records every CLI command path, option",
        "and JSON-schema digests for registered method and acquisition specifications.",
        "`dbs qualification interface` fails when the live snapshot differs. Contextual runtime evidence is",
        "declared separately. Changing the frozen snapshot requires an explicit new version. It covers software",
        "only and says nothing about qualification.",
        "",
        "## 8. Reproduce",
        "",
        "```sh",
        "uv sync --frozen",
        "uv run ruff check . && uv run ruff format --check . && uv run mypy",
        "uv run pytest",
        "uv run dbs qualification validate && uv run dbs qualification states",
        "uv run dbs qualification interface",
        "uv run dbs agreement run --out /tmp/agreement.json",
        "uv run python scripts/build_verification.py --check",
        "```",
        "",
    ]
    return "\n".join(out)


def disposition(payload: dict) -> str:
    gate = payload["m3_gate"]
    states = payload["states"]
    verified = sum(len(s["verified_m3"]) for s in states)
    pending = sum(len(s["unverified_m3"]) for s in states)
    lines = [
        "# M3 disposition under Policy A (RES-675)",
        "",
        "<!-- GENERATED by scripts/build_verification.py; do not edit -->",
        "",
        f"**M3 {'PASS' if gate['passed'] else 'FAIL'}** with {gate['engineering_verified']} of "
        f"{gate['total_subfamilies']} subfamilies engineering verified.",
        f"{verified} of {verified + pending} A-M/O computational cells verified, with {pending} open.",
        "",
        "| Subfamily | State | Verified | Open | Empirical records |",
        "| -- | -- | -- | -- | -- |",
    ]
    for state in states:
        verified_cells = ", ".join(state["verified_m3"]) or "—"
        pending_cells = ", ".join(state["unverified_m3"]) or "—"
        lines.append(
            f"| {state['subfamily']} | {state['state']} | {verified_cells} | {pending_cells} | "
            f"{len(state['empirical_records'])} |"
        )
    lines += [
        "",
        "Physical-device validity and empirical interchangeability are assessed separately.",
        "",
        "## Downstream readiness",
        "",
        "M4 engineering qualification is complete under staged Option B for the admitted native LPS",
        "reference in the [M4 report](graders-v0.1.md). M5 can proceed on individually admitted",
        "references under its existing issues. Full M3 remains a prerequisite for full-scope",
        "M8/M9 qualification and frozen release.",
        "",
        "The [engine verification report](engine-v0.1.md) lists the detailed evidence and owners.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload, text = build()
    disposition_text = disposition(payload)
    rendered = json.dumps(payload, indent=2, sort_keys=True, allow_nan=False) + "\n"
    if args.check:
        if failed := payload["case_totals"]["failed"]:
            print(f"FAIL verification matrix: {', '.join(failed)}", file=sys.stderr)
            return 1
        committed = json.loads(JSON_PATH.read_text()) if JSON_PATH.exists() else None
        if committed != json.loads(rendered) or not MD_PATH.exists() or MD_PATH.read_text() != text:
            print("FAIL stale verification report", file=sys.stderr)
            return 1
        if not DISPOSITION.exists() or DISPOSITION.read_text() != disposition_text:
            print("FAIL stale M3 disposition", file=sys.stderr)
            return 1
        print("verification report up to date")
        return 0
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(rendered, encoding="utf-8")
    MD_PATH.write_text(text, encoding="utf-8")
    DISPOSITION.write_text(disposition_text, encoding="utf-8")
    print(f"wrote {JSON_PATH} and {MD_PATH}")
    return 0 if payload["case_totals"]["failed"] == [] else 1


if __name__ == "__main__":
    raise SystemExit(main())
